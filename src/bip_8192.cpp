namespace {

constexpr const char* MANIFEST_NAME = "manifest.json";
constexpr const char* ENV_WORDLIST_DIR = "BUCKS_WORDLIST_DIR";

struct Registry {
    std::string dir;
    std::vector<std::shared_ptr<const Wordlist>> lists;   // manifest order
    std::string defaultLang;
};

std::mutex g_mutex;
std::string g_overrideDir;                   // setWordlistDir()
std::shared_ptr<const Registry> g_registry;  // last successful load

std::string executableDir() {
    std::string path;
#if defined(__APPLE__)
    uint32_t size = 0;
    _NSGetExecutablePath(nullptr, &size);
    std::vector<char> buf(size + 1, '\0');
    if (size == 0 || _NSGetExecutablePath(buf.data(), &size) != 0) return "";
    path.assign(buf.data());
#elif defined(_WIN32)
    char buf[MAX_PATH];
    DWORD n = GetModuleFileNameA(nullptr, buf, MAX_PATH);
    if (n == 0 || n >= MAX_PATH) return "";
    path.assign(buf, n);
#elif defined(__linux__)
    char buf[4096];
    ssize_t n = readlink("/proc/self/exe", buf, sizeof(buf) - 1);
    if (n <= 0) return "";
    path.assign(buf, static_cast<size_t>(n));
#else
    return "";
#endif
    std::error_code ec;
    fs::path p = fs::weakly_canonical(fs::path(path), ec);
    if (ec) p = fs::absolute(fs::path(path), ec);
    if (ec) return "";
    return p.parent_path().string();
}

bool hasManifest(const std::string& dir) {
    std::error_code ec;
    return !dir.empty() && fs::is_regular_file(fs::path(dir) / MANIFEST_NAME, ec);
}

// Caller holds g_mutex.
std::string resolveDirLocked(std::string* err) {
    if (!g_overrideDir.empty()) return g_overrideDir;
    if (const char* env = std::getenv(ENV_WORDLIST_DIR)) {
        if (*env) return env;
    }

    std::vector<std::string> candidates;
    std::string exe = executableDir();
    if (!exe.empty()) {
        candidates.push_back((fs::path(exe) / ".." / "wordlists").lexically_normal().string());
        candidates.push_back((fs::path(exe) / "wordlists").string());
    }
#ifdef BUCKS_SOURCE_DIR
    candidates.push_back((fs::path(BUCKS_SOURCE_DIR) / "wordlists").string());
#endif
    candidates.push_back("./wordlists");

    for (const auto& c : candidates)
        if (hasManifest(c)) return c;

    if (err) {
        std::string tried;
        for (const auto& c : candidates) tried += (tried.empty() ? "" : ", ") + c;
        *err = std::string("no wordlists directory with ") + MANIFEST_NAME +
               " found (set " + ENV_WORDLIST_DIR + "; tried: " + tried + ")";
    }
    return "";
}

std::shared_ptr<const Registry> loadRegistryFrom(const std::string& dir, std::string* err) {
    auto fail = [&](const std::string& why) {
        if (err) *err = "wordlists in '" + dir + "': " + why;
        return std::shared_ptr<const Registry>();
    };

    fs::path manifestPath = fs::path(dir) / MANIFEST_NAME;
    std::ifstream in(manifestPath, std::ios::binary);
    if (!in) return fail(std::string("cannot open ") + MANIFEST_NAME);

    nlohmann::json m;
    try {
        in >> m;
    } catch (const std::exception& e) {
        return fail(std::string(MANIFEST_NAME) + " is not valid JSON: " + e.what());
    }
    if (!m.is_object() || !m.contains("version") || !m["version"].is_number_integer() ||
        m["version"].get<int>() != 2)
        return fail(std::string(MANIFEST_NAME) + " must have \"version\": 2");
    if (!m.contains("lists") || !m["lists"].is_array() || m["lists"].empty())
        return fail(std::string(MANIFEST_NAME) + " must have a non-empty \"lists\" array");

    auto reg = std::make_shared<Registry>();
    reg->dir = dir;
    std::unordered_set<std::string> seenLang;

    for (const auto& item : m["lists"]) {
        if (!item.is_object()) return fail("list entry is not an object");
        for (const char* key : {"lang", "file", "normalizer", "status"}) {
            if (!item.contains(key) || !item[key].is_string() || item[key].get<std::string>().empty())
                return fail(std::string("list entry is missing \"") + key + "\"");
        }
        std::string lang = item["lang"].get<std::string>();
        std::string file = item["file"].get<std::string>();
        std::string normalizer = item["normalizer"].get<std::string>();
        std::string status = item["status"].get<std::string>();

        if (!seenLang.insert(lang).second) return fail("duplicate lang '" + lang + "'");
        if (hasInternalSpace(lang)) return fail("lang '" + lang + "' contains whitespace");
        if (file.find('/') != std::string::npos || file.find('\\') != std::string::npos ||
            file.find("..") != std::string::npos)
            return fail("file '" + file + "' must be a plain file name inside the wordlists directory");

        auto list = std::make_shared<Wordlist>();
        std::string listErr;
        if (!loadWordlistFile((fs::path(dir) / file).string(), lang, normalizer, status, *list, &listErr))
            return fail(listErr);
        reg->lists.push_back(std::move(list));
    }

    for (const auto& l : reg->lists) {
        if (l->status == "dev" || l->status == "release") { reg->defaultLang = l->lang; break; }
    }
    if (reg->defaultLang.empty())
        return fail(std::string(MANIFEST_NAME) + " has no list with status \"dev\" or \"release\"");

    return reg;
}

// Returns the cached registry for the currently resolved directory, loading
// (or reloading, when the directory changed or `force` is set) as needed.
std::shared_ptr<const Registry> currentRegistry(std::string* err, bool force = false) {
    std::lock_guard<std::mutex> lock(g_mutex);
    std::string dir = resolveDirLocked(err);
    if (dir.empty()) { g_registry.reset(); return nullptr; }
    if (!force && g_registry && g_registry->dir == dir) return g_registry;

    auto reg = loadRegistryFrom(dir, err);
    g_registry = reg;   // null on failure: nothing stale survives
    return reg;
}

std::shared_ptr<const Wordlist> pickList(const Registry& reg, const std::string& lang) {
    std::string want = lang.empty() ? reg.defaultLang : lang;
    for (const auto& l : reg.lists)
        if (l->lang == want) return l;
    return nullptr;
}

} // namespace

void setWordlistDir(const std::string& dir) {
    std::lock_guard<std::mutex> lock(g_mutex);
    g_overrideDir = dir;
    g_registry.reset();
}

std::string resolveWordlistDir(std::string* err) {
    std::lock_guard<std::mutex> lock(g_mutex);
    return resolveDirLocked(err);
}

bool loadWordlists(std::string* err) {
    return currentRegistry(err, /*force=*/true) != nullptr;
}

std::vector<std::string> mnemonicLanguages(std::string* err) {
    std::vector<std::string> langs;
    auto reg = currentRegistry(err);
    if (!reg) return langs;
    for (const auto& l : reg->lists) langs.push_back(l->lang);
    return langs;
}

std::string defaultMnemonicLanguage(std::string* err) {
    auto reg = currentRegistry(err);
    return reg ? reg->defaultLang : "";
}

std::shared_ptr<const Wordlist> findWordlist(const std::string& lang, std::string* err) {
    auto reg = currentRegistry(err);
    if (!reg) return nullptr;
    auto list = pickList(*reg, lang);
    if (!list && err) *err = "unknown word list language '" + lang + "'";
    return list;
}

WordlistCheck checkWordlistSet() {
    WordlistCheck r;
    std::string err;
    auto reg = currentRegistry(&err);
    if (!reg) {
        r.errors.push_back("word lists could not be loaded: " + err);
        return r;
    }
    const auto& lists = reg->lists;
    for (const auto& l : lists) {
        if (l->entries.size() != MNEMONIC_WORDLIST_SIZE)
            r.errors.push_back(l->lang + ": " + std::to_string(l->entries.size()) + " entries, expected 2048");
        if (l->status == "test" || l->status == "dev") continue;   // placeholders are exempt from the shape rules
        if (l->normalizer == "latin") {
            for (size_t i = 0; i < l->entries.size(); ++i) {
                const std::string& w = l->entries[i];
                const bool plain = !w.empty() && std::all_of(w.begin(), w.end(),
                                                             [](char c) { return c >= 'a' && c <= 'z'; });
                if (!plain)
                    r.errors.push_back(l->lang + " #" + std::to_string(i) + " '" + w + "': only a-z allowed");
            }
        }
        std::unordered_map<std::string, std::vector<size_t>> byPrefix;
        for (size_t i = 0; i < l->entries.size(); ++i) {
            std::string norm;
            if (normalizeMnemonicWord(l->normalizer, l->entries[i], norm) && l->normalizer == "latin" && norm.size() >= 4)
                byPrefix[norm.substr(0, 4)].push_back(i);
        }
        size_t shared = 0;
        for (const auto& kv : byPrefix) if (kv.second.size() > 1) shared += kv.second.size();
        if (shared)
            r.warnings.push_back(l->lang + ": " + std::to_string(shared) + " words share their first four letters with another word");
    }
    for (size_t a = 0; a < lists.size(); ++a) {
        for (size_t b = a + 1; b < lists.size(); ++b) {
            // "dev" and "test" lists are placeholders: they exist to be replaced, no real wallet depends on them.
            if (lists[a]->status == "test" || lists[b]->status == "test" ||
                lists[a]->status == "dev" || lists[b]->status == "dev") continue;
            size_t reported = 0;
            for (size_t i = 0; i < lists[a]->entries.size(); ++i) {
                std::string na;
                if (!normalizeMnemonicWord(lists[a]->normalizer, lists[a]->entries[i], na)) continue;
                auto itB = lists[b]->index.find(na);
                if (itB == lists[b]->index.end()) {
                    // The same typed text can also be a word of list b under b's own folding.
                    std::string nb;
                    if (!normalizeMnemonicWord(lists[b]->normalizer, lists[a]->entries[i], nb)) continue;
                    itB = lists[b]->index.find(nb);
                    if (itB == lists[b]->index.end()) continue;
                }
                if (itB->second != i && reported++ < 20)
                    r.errors.push_back(lists[a]->lang + " #" + std::to_string(i) + " '" + lists[a]->entries[i] + "' is " +
                                       lists[b]->lang + " #" + std::to_string(itB->second) + ": same spelling, different index");
            }
        }
    }
    return r;
}

