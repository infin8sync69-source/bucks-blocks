namespace {

bool isAsciiSpace(unsigned char c) {
    return c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f' || c == '\v';
}

std::string trimAscii(const std::string& s) {
    size_t b = 0, e = s.size();
    while (b < e && isAsciiSpace(static_cast<unsigned char>(s[b]))) ++b;
    while (e > b && isAsciiSpace(static_cast<unsigned char>(s[e - 1]))) --e;
    return s.substr(b, e - b);
}

bool hasInternalSpace(const std::string& s) {
    for (unsigned char c : s)
        if (isAsciiSpace(c)) return true;
    return false;
}

// Strict UTF-8 decoder: rejects overlong forms, surrogates and > U+10FFFF.
bool utf8Decode(const std::string& in, std::vector<uint32_t>& out) {
    out.clear();
    out.reserve(in.size());
    size_t i = 0;
    while (i < in.size()) {
        unsigned char c = static_cast<unsigned char>(in[i]);
        uint32_t cp;
        size_t len;
        if (c < 0x80)       { cp = c;        len = 1; }
        else if (c < 0xC2)  { return false; }
        else if (c < 0xE0)  { cp = c & 0x1F; len = 2; }
        else if (c < 0xF0)  { cp = c & 0x0F; len = 3; }
        else if (c < 0xF5)  { cp = c & 0x07; len = 4; }
        else                { return false; }
        if (i + len > in.size()) return false;
        for (size_t k = 1; k < len; ++k) {
            unsigned char cc = static_cast<unsigned char>(in[i + k]);
            if ((cc & 0xC0) != 0x80) return false;
            cp = (cp << 6) | (cc & 0x3F);
        }
        if ((len == 3 && cp < 0x800) || (len == 4 && cp < 0x10000)) return false;   // overlong
        if (cp >= 0xD800 && cp <= 0xDFFF) return false;                            // surrogate
        if (cp > 0x10FFFF) return false;
        out.push_back(cp);
        i += len;
    }
    return true;
}

void utf8Append(std::string& out, uint32_t cp) {
    if (cp < 0x80) {
        out += static_cast<char>(cp);
    } else if (cp < 0x800) {
        out += static_cast<char>(0xC0 | (cp >> 6));
        out += static_cast<char>(0x80 | (cp & 0x3F));
    } else if (cp < 0x10000) {
        out += static_cast<char>(0xE0 | (cp >> 12));
        out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
        out += static_cast<char>(0x80 | (cp & 0x3F));
    } else {
        out += static_cast<char>(0xF0 | (cp >> 18));
        out += static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
        out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
        out += static_cast<char>(0x80 | (cp & 0x3F));
    }
}

// ============================================================
// ARABIC FOLD TABLES (code points; keep in sync with tools/make_dev_wordlist.py)
// ============================================================

struct CpRange { uint32_t lo, hi; };

constexpr CpRange ARABIC_STRIP_RANGES[] = {
    {0x064B, 0x065F},   // harakat, shadda, sukun, small high/low marks
    {0x0670, 0x0670},   // superscript alef
    {0x06D6, 0x06ED},   // Quranic annotation marks
    {0x0640, 0x0640},   // tatweel
    {0x200B, 0x200F},   // zero-width space/joiners, LRM/RLM
    {0x061C, 0x061C},   // Arabic letter mark
    {0xFEFF, 0xFEFF},   // zero-width no-break space
};

struct CpMap { uint32_t from, to; };

constexpr CpMap ARABIC_LETTER_MAP[] = {
    {0x0623, 0x0627}, {0x0625, 0x0627}, {0x0622, 0x0627}, {0x0671, 0x0627},   // alef variants
    {0x0649, 0x064A}, {0x06CC, 0x064A}, {0x0626, 0x064A},                     // yeh variants
    {0x06A9, 0x0643},                                                         // keheh -> kaf
    {0x0629, 0x0647}, {0x06C1, 0x0647}, {0x06D5, 0x0647},                     // heh variants
    {0x0624, 0x0648},                                                         // waw with hamza
};

bool arabicStripped(uint32_t cp) {
    for (const auto& r : ARABIC_STRIP_RANGES)
        if (cp >= r.lo && cp <= r.hi) return true;
    return false;
}

uint32_t arabicMapped(uint32_t cp) {
    for (const auto& m : ARABIC_LETTER_MAP)
        if (m.from == cp) return m.to;
    return cp;
}

// NFKD of one code point via the generated Arabic-block table (sorted by cp).
void arabicNfkd(uint32_t cp, std::vector<uint32_t>& out) {
    const ArabicNfkdRow* begin = ARABIC_NFKD_TABLE;
    const ArabicNfkdRow* end = ARABIC_NFKD_TABLE + ARABIC_NFKD_ROWS;
    const ArabicNfkdRow* it = std::lower_bound(begin, end, cp,
        [](const ArabicNfkdRow& row, uint32_t v) { return row.cp < v; });
    if (it != end && it->cp == cp) {
        for (size_t k = 0; k < it->length; ++k)
            out.push_back(ARABIC_NFKD_POOL[it->offset + k]);
    } else {
        out.push_back(cp);
    }
}

} // namespace

bool arabicFold(const std::string& in, std::string& out) {
    out.clear();
    std::vector<uint32_t> cps;
    if (!utf8Decode(in, cps)) return false;

    std::vector<uint32_t> decomposed;
    decomposed.reserve(cps.size() + 8);
    for (uint32_t cp : cps) arabicNfkd(cp, decomposed);

    for (uint32_t cp : decomposed) {
        if (arabicStripped(cp)) continue;
        utf8Append(out, arabicMapped(cp));
    }
    return true;
}

