const char* mnemonicErrorString(MnemonicError err) {
    switch (err) {
        case MnemonicError::OK:                     return "ok";
        case MnemonicError::INVALID_ENTROPY_SIZE:   return "entropy must be 16 or 32 bytes";
        case MnemonicError::WORDLIST_LOAD_FAILED:   return "word lists could not be loaded";
        case MnemonicError::INVALID_WORD_COUNT:     return "phrase must have 13 or 25 words";
        case MnemonicError::INVALID_WORD:           return "a word is not in any loaded word list";
        case MnemonicError::CHECKSUM_MISMATCH:      return "checksum mismatch (a word is wrong or out of order)";
        case MnemonicError::UNKNOWN_LANGUAGE:       return "unknown word list language";
        case MnemonicError::AMBIGUOUS_LANGUAGE:     return "phrase is valid in more than one language";
        case MnemonicError::SEED_DERIVATION_FAILED: return "seed derivation failed";
    }
    return "unknown mnemonic error";
}

