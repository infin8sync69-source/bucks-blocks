bool isKnownMnemonicNormalizer(const std::string& name) {
    return name == "exact" || name == "arabic" || name == "latin";
}

bool normalizeMnemonicWord(const std::string& normalizer,
                           const std::string& word,
                           std::string& out) {
    out.clear();
    std::string w = trimAscii(word);
    if (w.empty()) return false;

    if (normalizer == "exact") {
        out = w;
    } else if (normalizer == "latin") {
        out.reserve(w.size());
        for (unsigned char c : w) {
            if (c >= 0x80) { out.clear(); return false; }
            out += static_cast<char>((c >= 'A' && c <= 'Z') ? c + ('a' - 'A') : c);
        }
    } else if (normalizer == "arabic") {
        if (!arabicFold(w, out)) { out.clear(); return false; }
    } else {
        return false;
    }
    return !out.empty();
}

std::vector<std::string> splitMnemonic(const std::string& phrase) {
    std::vector<std::string> words;
    std::string cur;
    for (unsigned char c : phrase) {
        if (isAsciiSpace(c)) {
            if (!cur.empty()) { words.push_back(cur); cur.clear(); }
        } else {
            cur += static_cast<char>(c);
        }
    }
    if (!cur.empty()) words.push_back(cur);
    return words;
}

