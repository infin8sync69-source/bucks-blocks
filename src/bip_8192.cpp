std::string mnemonicFromEntropy(const std::vector<uint8_t>& entropy,
                                const std::string& lang,
                                MnemonicError* err) {
    if (err) *err = MnemonicError::OK;
    if (!isSupportedMnemonicEntropySize(entropy.size())) {
        if (err) *err = MnemonicError::INVALID_ENTROPY_SIZE;
        return {};
    }

    auto reg = currentRegistry(nullptr);
    if (!reg) { if (err) *err = MnemonicError::WORDLIST_LOAD_FAILED; return {}; }
    auto list = pickList(*reg, lang);
    if (!list) { if (err) *err = MnemonicError::UNKNOWN_LANGUAGE; return {}; }

    size_t entropyBits = entropy.size() * 8;
    size_t checksumBits = mnemonicChecksumBits(entropyBits);
    Hash256 hash = sha256(entropy);

    BitVec bits = bytesToBits(entropy);
    BitVec hashBits = bytesToBits(std::vector<uint8_t>(hash.begin(), hash.end()));
    bits.insert(bits.end(), hashBits.begin(), hashBits.begin() + checksumBits);

    size_t wordCount = mnemonicWordCount(entropyBits);
    std::string out;
    for (size_t i = 0; i < wordCount; ++i) {
        size_t idx = 0;
        for (size_t b = 0; b < MNEMONIC_WORD_BITS; ++b)
            idx = (idx << 1) | bits[i * MNEMONIC_WORD_BITS + b];
        if (i) out += ' ';
        out += list->entries[idx];
    }
    cleanse(bits);
    return out;
}

MnemonicError mnemonicToEntropy(const std::string& phrase,
                                std::vector<uint8_t>& entropyOut,
                                std::string* langOut,
                                const std::string& lang) {
    entropyOut.clear();
    if (langOut) langOut->clear();

    std::vector<std::string> words = splitMnemonic(phrase);
    size_t entropyBytes = entropyBytesForWordCount(words.size());
    if (entropyBytes == 0) return MnemonicError::INVALID_WORD_COUNT;

    auto reg = currentRegistry(nullptr);
    if (!reg) return MnemonicError::WORDLIST_LOAD_FAILED;

    std::vector<std::shared_ptr<const Wordlist>> candidates;
    if (lang.empty()) {
        candidates = reg->lists;
    } else {
        auto list = pickList(*reg, lang);
        if (!list) return MnemonicError::UNKNOWN_LANGUAGE;
        candidates.push_back(list);
    }

    std::vector<uint8_t> found;
    std::string foundLang;
    size_t successes = 0;
    bool anyResolved = false;
    for (const auto& list : candidates) {
        std::vector<uint8_t> entropy;
        bool resolved = false;
        if (decodeWithList(*list, words, entropyBytes, entropy, resolved)) {
            ++successes;
            if (successes == 1) { found = std::move(entropy); foundLang = list->lang; }
            else cleanse(entropy);
        }
        anyResolved |= resolved;
    }

    if (successes == 1) {
        entropyOut = std::move(found);
        if (langOut) *langOut = foundLang;
        return MnemonicError::OK;
    }
    cleanse(found);
    if (successes > 1) return MnemonicError::AMBIGUOUS_LANGUAGE;
    return anyResolved ? MnemonicError::CHECKSUM_MISMATCH : MnemonicError::INVALID_WORD;
}

MnemonicError validateMnemonic(const std::string& phrase,
                               std::string* langOut,
                               const std::string& lang) {
    std::vector<uint8_t> entropy;
    MnemonicError err = mnemonicToEntropy(phrase, entropy, langOut, lang);
    cleanse(entropy);
    return err;
}

std::string convertMnemonic(const std::string& phrase,
                            const std::string& targetLang,
                            MnemonicError* err) {
    std::vector<uint8_t> entropy;
    MnemonicError e = mnemonicToEntropy(phrase, entropy);
    if (e != MnemonicError::OK) { if (err) *err = e; return {}; }
    std::string out = mnemonicFromEntropy(entropy, targetLang, err);
    cleanse(entropy);
    return out;
}

// ============================================================
// SEED DERIVATION
// ============================================================

std::vector<uint8_t> seedFromEntropy(const std::vector<uint8_t>& entropy,
                                     const std::string& passphrase) {
    if (!isSupportedMnemonicEntropySize(entropy.size())) return {};

    std::string salt = std::string(MNEMONIC_SALT_PREFIX) + passphrase;   // bytes verbatim
    std::vector<uint8_t> seed(MNEMONIC_SEED_BYTES);
    bool ok = pbkdf2_hmac_sha512(
        reinterpret_cast<const char*>(entropy.data()), entropy.size(),
        salt.data(), salt.size(),
        MNEMONIC_PBKDF2_ROUNDS,
        seed.data(), seed.size()
    );
    OPENSSL_cleanse(&salt[0], salt.size());
    if (!ok) { cleanse(seed); return {}; }
    return seed;
}

std::vector<uint8_t> mnemonicToSeed(const std::string& phrase,
                                    const std::string& passphrase,
                                    MnemonicError* err) {
    std::vector<uint8_t> entropy;
    MnemonicError e = mnemonicToEntropy(phrase, entropy);
    if (e != MnemonicError::OK) { if (err) *err = e; return {}; }
    std::vector<uint8_t> seed = seedFromEntropy(entropy, passphrase);
    cleanse(entropy);
    if (seed.empty()) { if (err) *err = MnemonicError::SEED_DERIVATION_FAILED; return {}; }
    if (err) *err = MnemonicError::OK;
    return seed;
}

