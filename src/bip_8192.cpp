// ============================================================================
// Bucks Mnemonic v2
// ============================================================================
//
// Replaces the BIP-8192 scheme (13-bit words over an 8192-entry list of
// Quranic word forms). That list could not be typed reliably (only ~5,650 of
// its 8,192 forms are distinct without diacritics) and the loader rejected it,
// which left every wallet with an empty mnemonic and one fixed key (CRY-1).
//
// SCHEME
//   * Word lists have exactly 2048 entries, so one word carries 11 bits.
//   * Supported entropy sizes and the resulting phrases:
//         128 bits -> 15-bit checksum -> 13 words (143 bits)
//         256 bits -> 19-bit checksum -> 25 words (275 bits)
//     The checksum is the first CS bits of SHA-256(entropy); CS is the smallest
//     value >= ENT/16 that makes ENT+CS a multiple of 11 (mnemonicChecksumBits).
//     Any other entropy size or word count is rejected.
//   * Bits are consumed MSB first; word i is bits [11*i, 11*i+11) as an index.
//
// LANGUAGES
//   * wordlists/manifest.json lists the languages:
//       {"version":2,"lists":[{"lang":"ar-dev","file":"ar-dev-2048.txt",
//                              "normalizer":"arabic","status":"dev"}]}
//   * Lists are INDEX-ALIGNED: entry i of every list means the same 11-bit
//     value, so convertMnemonic() re-encodes a phrase in another language
//     without changing the entropy. Future English/Urdu/... lists must keep
//     that alignment.
//   * Decoding auto-detects the language: every loaded list whose normalizer
//     resolves all words and whose checksum validates is a candidate; exactly
//     one must succeed (AMBIGUOUS_LANGUAGE otherwise).
//   * The default language for new wallets is the first "dev"/"release" list.
//   * "ar-dev" is a clearly labelled DEV placeholder generated by
//     tools/make_dev_wordlist.py; the release Arabic list is produced by a
//     separate review process.
//
// NORMALIZERS (how typed words are matched to list entries)
//   "exact"  : UTF-8 byte-exact after trimming ASCII whitespace.
//   "latin"  : ASCII lowercase; any non-ASCII byte is rejected.
//   "arabic" : fold typed Arabic to one canonical form, with explicit
//              code-point tables (no ICU):
//              1. NFKD of the Arabic blocks (include/arabic_nfkd_table.h,
//                 generated from Unicode data): presentation forms and
//                 ligatures become base letters; the precomposed hamza/madda
//                 letters (U+0622-0626, U+06C0, U+06C2, U+06D3) become base
//                 letter + combining mark.
//              2. Remove U+064B-U+065F, U+0670, U+06D6-U+06ED (harakat and
//                 Quranic marks), U+0640 (tatweel), U+200B-U+200F, U+061C,
//                 U+FEFF (zero-width/direction characters).
//              3. Map أ إ آ ٱ -> ا; ى and ی (U+06CC) -> ي; ک (U+06A9) -> ك;
//                 ة, ہ (U+06C1), ە (U+06D5) -> ه; ؤ -> و; ئ -> ي.
//              Step 1 decomposes before step 2 strips, so the result is the
//              same whether the input was precomposed (NFC/NFKC) or not, and
//              it is already NFC (no combining marks remain). This equals
//              "NFKC, then strip, then map" except that ۀ/ۂ/ۓ are folded
//              consistently with their decomposed spellings.
//   Loading validates every list: exactly 2048 non-empty entries (lines that
//   start with '#' are comments), no internal whitespace, every entry accepted
//   by the normalizer and unique under it. Any failure is an error; nothing
//   is silently skipped. Display forms (what the user sees) are the raw lines.
//
// SEED (entropy-canonical, language independent)
//   seed = PBKDF2-HMAC-SHA512(password = raw entropy bytes,
//                             salt     = "bucks-mnemonic-v2" || passphrase,
//                             2048 iterations, 64 bytes)
//   The passphrase's UTF-8 bytes are used verbatim: no normalisation, so it
//   must be typed exactly as it was chosen. Because the seed comes from the
//   entropy, the same wallet is reached from any language's phrase.
//
// WORDLIST DIRECTORY (first hit wins; see resolveWordlistDir)
//   setWordlistDir() > $BUCKS_WORDLIST_DIR > <exe>/../wordlists >
//   <exe>/wordlists > BUCKS_SOURCE_DIR/wordlists > ./wordlists.
//   The two explicit settings are used as given (no fallback) so a wrong
//   configuration fails loudly instead of silently picking another list.
// ============================================================================

