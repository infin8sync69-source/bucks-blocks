bool loadWordlistFile(const std::string& path,
                      const std::string& lang,
                      const std::string& normalizer,
                      const std::string& status,
                      Wordlist& out,
                      std::string* err) {
    auto fail = [&](const std::string& why) {
        if (err) *err = "wordlist '" + path + "': " + why;
        out = Wordlist{};
        return false;
    };

    if (!isKnownMnemonicNormalizer(normalizer))
        return fail("unknown normalizer '" + normalizer + "'");

    std::ifstream in(path, std::ios::binary);
    if (!in) return fail("cannot open");

    Wordlist list;
    list.lang = lang;
    list.normalizer = normalizer;
    list.status = status;
    list.entries.reserve(MNEMONIC_WORDLIST_SIZE);

    std::string line;
    size_t lineNo = 0;
    while (std::getline(in, line)) {
        ++lineNo;
        if (lineNo == 1 && line.size() >= 3 &&
            static_cast<unsigned char>(line[0]) == 0xEF &&
            static_cast<unsigned char>(line[1]) == 0xBB &&
            static_cast<unsigned char>(line[2]) == 0xBF)
            line.erase(0, 3);   // UTF-8 BOM
        std::string entry = trimAscii(line);
        if (entry.empty() || entry[0] == '#') continue;
        if (hasInternalSpace(entry))
            return fail("line " + std::to_string(lineNo) + " contains whitespace");
        if (list.entries.size() >= MNEMONIC_WORDLIST_SIZE)
            return fail("more than " + std::to_string(MNEMONIC_WORDLIST_SIZE) + " entries");

        std::string norm;
        if (!normalizeMnemonicWord(normalizer, entry, norm))
            return fail("line " + std::to_string(lineNo) + " is rejected by the '" + normalizer + "' normalizer");
        if (list.index.count(norm))
            return fail("line " + std::to_string(lineNo) + " duplicates entry " +
                        std::to_string(list.index[norm] + 1) + " under the '" + normalizer + "' normalizer");

        list.index.emplace(norm, static_cast<uint16_t>(list.entries.size()));
        list.entries.push_back(entry);
    }
    if (in.bad()) return fail("read error");
    if (list.entries.size() != MNEMONIC_WORDLIST_SIZE)
        return fail("expected " + std::to_string(MNEMONIC_WORDLIST_SIZE) + " entries, found " +
                    std::to_string(list.entries.size()));

    out = std::move(list);
    return true;
}

