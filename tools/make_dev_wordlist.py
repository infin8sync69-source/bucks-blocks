#!/usr/bin/env python3
"""Build wordlists/ar-dev-2048.txt, the DEV placeholder list for Bucks Mnemonic v2.

Reads the legacy Quranic form list (wordlists/bip_8192.txt), applies the same
Arabic fold as the "arabic" normalizer in src/bip_8192.cpp, and keeps the
entries that are usable as typed, diacritic-free words:

  * the folded form is unique across the whole folded legacy list,
  * 3..7 letters after folding,
  * does not contain "الله" or "اله", and is not one of the bare "رب" forms.

The first 2048 survivors in file order are written, FOLDED (diacritic-free,
NFC), one per line.  This is NOT the release list: that will be built by the
documented review process (lemmas, exclusions, scholar review).

Usage: python3 tools/make_dev_wordlist.py [legacy.txt] [out.txt]
"""
import collections
import sys
import unicodedata

LIST_SIZE = 2048
MIN_LEN, MAX_LEN = 3, 7

EXCLUDE_SUBSTRINGS = ("الله", "اله")
EXCLUDE_EXACT = {"رب", "ربك", "ربكم", "ربه", "ربهم", "ربنا", "ربي"}

# Code-point tables shared with the C++ "arabic" normalizer (keep in sync).
STRIP_RANGES = [
    (0x064B, 0x065F),  # harakat, shadda, sukun, small high/low marks
    (0x0670, 0x0670),  # superscript alef
    (0x06D6, 0x06ED),  # Quranic annotation marks
    (0x0640, 0x0640),  # tatweel
    (0x200B, 0x200F),  # zero-width space/joiners, LRM/RLM
    (0x061C, 0x061C),  # Arabic letter mark
    (0xFEFF, 0xFEFF),  # zero-width no-break space
]
LETTER_MAP = {
    0x0623: 0x0627, 0x0625: 0x0627, 0x0622: 0x0627, 0x0671: 0x0627,  # alef variants
    0x0649: 0x064A, 0x06CC: 0x064A, 0x0626: 0x064A,                  # yeh variants
    0x06A9: 0x0643,                                                  # keheh -> kaf
    0x0629: 0x0647, 0x06C1: 0x0647, 0x06D5: 0x0647,                  # heh variants
    0x0624: 0x0648,                                                  # waw with hamza
}


def arabic_fold(word):
    """Same algorithm as Bucks::arabicFold(): NFKD, strip, map, NFC."""
    out = []
    for ch in unicodedata.normalize("NFKD", word):
        cp = ord(ch)
        if any(lo <= cp <= hi for lo, hi in STRIP_RANGES):
            continue
        out.append(chr(LETTER_MAP.get(cp, cp)))
    return unicodedata.normalize("NFC", "".join(out))


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "wordlists/bip_8192.txt"
    dst = sys.argv[2] if len(sys.argv) > 2 else "wordlists/ar-dev-2048.txt"

    with open(src, encoding="utf-8") as f:
        legacy = [line.strip() for line in f]
    legacy = [w for w in legacy if w and not w.startswith("#")]

    folded = [arabic_fold(w) for w in legacy]
    counts = collections.Counter(folded)

    chosen = []
    for form in folded:
        if counts[form] != 1:
            continue
        if not MIN_LEN <= len(form) <= MAX_LEN:
            continue
        if any(s in form for s in EXCLUDE_SUBSTRINGS) or form in EXCLUDE_EXACT:
            continue
        chosen.append(form)
        if len(chosen) == LIST_SIZE:
            break

    if len(chosen) != LIST_SIZE:
        sys.exit("only %d candidates, need %d" % (len(chosen), LIST_SIZE))

    # Self-check: the written forms must stay distinct and fixed under the fold.
    assert len(set(chosen)) == LIST_SIZE, "duplicate folded forms"
    for w in chosen:
        assert arabic_fold(w) == w, "fold is not idempotent for %r" % w
        assert not any(c.isspace() for c in w), "whitespace in %r" % w

    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Bucks DEV word list — placeholder derived from the legacy "
                "Quranic form list. NOT the release list. The release list will be "
                "built by the documented review process (lemmas, exclusions, "
                "scholar review).\n")
        f.write("# Generated by tools/make_dev_wordlist.py from %s "
                "(%d legacy forms, %d distinct folded, %d unique).\n"
                % (src, len(legacy), len(counts), sum(1 for c in counts.values() if c == 1)))
        for w in chosen:
            f.write(w + "\n")
    print("wrote %d words to %s" % (len(chosen), dst))


if __name__ == "__main__":
    main()
